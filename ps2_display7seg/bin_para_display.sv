module bin_para_display (
    input  logic [0:8] s_in,
    output logic [0:6] s_out
);

    // =========================================================
    // Display de 7 segmentos ATIVO-LOW
    //
    // s_out = {a,b,c,d,e,f,g}
    //
    // 0 -> segmento aceso
    // 1 -> segmento apagado
    // =========================================================

    always_comb begin

        // Padrão: display apagado
        s_out = 7'b1111111;

        case (s_in)

            // =================================================
            // NÚMEROS
            // =================================================

            9'h16: s_out = 7'b1111001; // 1
            9'h1E: s_out = 7'b0100100; // 2
            9'h26: s_out = 7'b0110000; // 3
            9'h25: s_out = 7'b0011001; // 4
            9'h2E: s_out = 7'b0010010; // 5
            9'h36: s_out = 7'b0000010; // 6
            9'h3D: s_out = 7'b1111000; // 7
            9'h3E: s_out = 7'b0000000; // 8
            9'h46: s_out = 7'b0010000; // 9
            9'h45: s_out = 7'b1000000; // 0


            // =================================================
            // PRIMEIRA LINHA DE LETRAS
            // Q W E R T Y U I O P
            // =================================================

            9'h15: s_out = 7'b0011000; // Q
            9'h1D: s_out = 7'b0101011; // W (aproximação)
            9'h24: s_out = 7'b0000110; // E
            9'h2D: s_out = 7'b0101111; // R
            9'h2C: s_out = 7'b0000111; // T
            9'h35: s_out = 7'b0010001; // Y
            9'h3C: s_out = 7'b1000001; // U
            9'h43: s_out = 7'b1111001; // I
            9'h44: s_out = 7'b1000000; // O
            9'h4D: s_out = 7'b0001100; // P


            // =================================================
            // SEGUNDA LINHA
            // A S D F G H J K L
            // =================================================

            9'h1C: s_out = 7'b0001000; // A
            9'h1B: s_out = 7'b0010010; // S
            9'h23: s_out = 7'b0100001; // D
            9'h2B: s_out = 7'b0001110; // F
            9'h34: s_out = 7'b0010000; // G
            9'h33: s_out = 7'b0001001; // H
            9'h3B: s_out = 7'b1110001; // J
            9'h42: s_out = 7'b0001001; // K (aproximação)
            9'h4B: s_out = 7'b1000111; // L


            // =================================================
            // TERCEIRA LINHA
            // Z X C V B N M
            // =================================================

            9'h1A: s_out = 7'b0100100; // Z
            9'h22: s_out = 7'b0001001; // X (aproximação)
            9'h21: s_out = 7'b1000110; // C
            9'h2A: s_out = 7'b1000001; // V
            9'h32: s_out = 7'b0000011; // B
            9'h31: s_out = 7'b0101011; // N (aproximação)
            9'h3A: s_out = 7'b0101011; // M (aproximação)


            // =================================================
            // ESPAÇO
            // =================================================

            9'h29: s_out = 7'b1111111;


            // =================================================
            // QUALQUER OUTRA TECLA
            // =================================================

            default: s_out = 7'b1111111;

        endcase
    end

endmodule
